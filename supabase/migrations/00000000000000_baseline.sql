CREATE OR REPLACE FUNCTION "public"."rls_auto_enable"() RETURNS "event_trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO 'pg_catalog'
    AS $$
DECLARE
  cmd record;
BEGIN
  FOR cmd IN
    SELECT *
    FROM pg_event_trigger_ddl_commands()
    WHERE command_tag IN ('CREATE TABLE', 'CREATE TABLE AS', 'SELECT INTO')
      AND object_type IN ('table','partitioned table')
  LOOP
     IF cmd.schema_name IS NOT NULL AND cmd.schema_name IN ('public') AND cmd.schema_name NOT IN ('pg_catalog','information_schema') AND cmd.schema_name NOT LIKE 'pg_toast%' AND cmd.schema_name NOT LIKE 'pg_temp%' THEN
      BEGIN
        EXECUTE format('alter table if exists %s enable row level security', cmd.object_identity);
        RAISE LOG 'rls_auto_enable: enabled RLS on %', cmd.object_identity;
      EXCEPTION
        WHEN OTHERS THEN
          RAISE LOG 'rls_auto_enable: failed to enable RLS on %', cmd.object_identity;
      END;
     ELSE
        RAISE LOG 'rls_auto_enable: skip % (either system schema or not in enforced list: %.)', cmd.object_identity, cmd.schema_name;
     END IF;
  END LOOP;
END;
$$;


ALTER FUNCTION "public"."rls_auto_enable"() OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."sync_audio_features_to_songs_v2"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    AS $$
begin
  update songs_v2
  set
    bpm = case when songs_v2.bpm is null then new.bpm else songs_v2.bpm end,
    start_time = new.start_time,
    end_time = new.end_time
  where id = new.song_id;
  return new;
end;
$$;


ALTER FUNCTION "public"."sync_audio_features_to_songs_v2"() OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."sync_audius_song_to_songs_v2"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    AS $$declare
  v_artist_id bigint;
begin
  if new.track_cid is not null and new.expired_stream_url is not null then
  if new.duration is not null and new.duration > 900 then
    return new;
  end if;

    if new.user_id is not null then
      insert into artists_v2 (name, provider, audius_artist_id)
      values (coalesce(new.user_name, 'Unknown'), 1, new.user_id)
      on conflict (audius_artist_id) do update set name = excluded.name
      returning id into v_artist_id;
    else
      v_artist_id := null;
    end if;

    insert into songs_v2 (
      title, bpm, duration, genre, mood, description,
      release_date, image, share_url, tags, provider,
      audius_provider_id, artist_id
    )
    values (
      coalesce(new.title, 'Untitled'),
      new.bpm,
      new.duration,
      new.genre,
      new.mood,
      new.description,
      new.release_date::timestamptz,
      new.artwork,
      'https://audius.co' || new.permalink,
      new.tags,
      1,
      new.audius_id,
      v_artist_id
    )
    on conflict (audius_provider_id) do update set
      title = excluded.title,
      bpm = excluded.bpm,
      duration = excluded.duration,
      genre = excluded.genre,
      mood = excluded.mood,
      description = excluded.description,
      release_date = excluded.release_date,
      image = excluded.image,
      share_url = excluded.share_url,
      tags = excluded.tags,
      artist_id = excluded.artist_id;
  end if;
  return new;
end;$$;


